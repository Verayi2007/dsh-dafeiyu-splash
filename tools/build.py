"""Build the splash: one visual source -> preview page + DSH client plugin.

Inputs : src/splash.css, src/splash.body.html, src/runtime.js, build/art.b64
Outputs: preview/preview.html, client.js
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
BUILD = ROOT / "build"
PKG = ROOT

import base64
ART_FILE = ROOT / "assets" / "feiyu.webp"
art = "data:image/webp;base64," + base64.b64encode(ART_FILE.read_bytes()).decode("ascii")

css = (SRC / "splash.css").read_text(encoding="utf-8-sig")
body = (SRC / "splash.body.html").read_text(encoding="utf-8-sig")
runtime = (SRC / "runtime.js").read_text(encoding="utf-8-sig")

css = css.replace("{{ART}}", art)
body = body.replace("{{ART}}", art)


def js(value):
    return json.dumps(value, ensure_ascii=False).replace("</", "<\\/")


preview = f"""<!doctype html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>大肥鱼开屏 · 预览</title>
<style>
  html, body {{ margin: 0; height: 100%; background: #04060e; overflow: hidden; }}
  #dfy-stage {{ position: fixed; inset: 0; }}
</style>
</head>
<body>
<div id="dfy-stage"></div>
<script>
var DFY_CSS = {js(css)};
var DFY_BODY = {js(body)};

{runtime}

window.__DAFEIYU_SPLASH__ = Object.assign({{ duration: 4600 }}, window.__DAFEIYU_SPLASH__ || {{}});

/* ?t=1800 定格到第 1800 毫秒：交给 runtime 在挂载时同步做完，截图不会再抓空 */
var freezeAt = Number(new URLSearchParams(location.search).get("t"));
if (freezeAt > 0) window.__DFY_FREEZE__ = freezeAt;

var dfyCtl = dfyCreateSplash(document.getElementById("dfy-stage"), {{}});
</script>
</body>
</html>
"""
(ROOT / "preview").mkdir(exist_ok=True)
(ROOT / "preview" / "preview.html").write_text(preview, encoding="utf-8")

client = f"""/* dsh-dafeiyu-splash — client half.
 * Generated by build/build.py from src/ — edit the sources, not this file.
 * Registers one `shell.overlay` entry and plays the opening animation once.
 */
window.__ModuleLoader__.load({{
  id: "dsh-dafeiyu-splash",
  factory(require) {{
    var React = require("react");
    var h = React.createElement;

    var DFY_CSS = {js(css)};
    var DFY_BODY = {js(body)};

{runtime}

    var portal = null;
    try {{
      var rd = require("react-dom");
      if (rd && typeof rd.createPortal === "function") portal = rd.createPortal;
    }} catch (err) {{
      /* portal is optional: the overlay layer is already frame-wide */
    }}

    function mark(state) {{
      try {{
        document.documentElement.setAttribute("data-dafeiyu-splash", state);
      }} catch (err) {{}}
    }}

    function options() {{
      var cfg = (typeof window !== "undefined" && window.__DAFEIYU_SPLASH__) || {{}};
      return cfg && typeof cfg === "object" ? cfg : {{}};
    }}

    var played = false;

    function SplashOverlay() {{
      var hostRef = React.useRef(null);
      var state = React.useState(true);
      var live = state[0];
      var setLive = state[1];

      React.useEffect(function () {{
        var cfg = options();
        if (!live || played || cfg.disabled === true || !hostRef.current) {{
          if (!live) mark("done");
          return undefined;
        }}
        played = true;
        mark("playing");

        var ctl = dfyCreateSplash(hostRef.current, {{
          duration: cfg.duration,
          title: cfg.title,
          subtitle: cfg.subtitle,
          hint: cfg.hint,
          onDone: function () {{
            mark("done");
            setLive(false);
          }},
        }});

        return function () {{
          ctl.destroy();
        }};
      }}, [live]);

      if (!live) return null;
      var node = h("div", {{
        ref: hostRef,
        className: "dfy-host",
        "data-plugin": "dsh-dafeiyu-splash",
      }});
      return portal ? portal(node, document.body) : node;
    }}

    return {{
      name: "dafeiyu-splash",
      inject: ["slots"],
      apply(ctx) {{
        var slots = ctx.get("slots");
        if (!slots) return;
        var register = function () {{
          return slots.register(
            {{ name: "shell.overlay", id: "dafeiyu-splash", order: 120 }},
            SplashOverlay
          );
        }};
        if (typeof slots.inject === "function") {{
          ctx.effect(function () {{
            return slots.inject("shell.overlay", register);
          }}, "dafeiyu-splash: opening overlay");
        }} else {{
          ctx.effect(register, "dafeiyu-splash: opening overlay");
        }}
      }},
    }};
  }},
}});
"""
PKG.mkdir(exist_ok=True)
(PKG / "client.js").write_text(client, encoding="utf-8")

print(f"preview -> preview/preview.html ({len(preview)} chars)")
print(f"client  -> package/client.js ({len(client)} chars)")
